/** いま入力欄にいるか（ヘルプを開いた瞬間の状態） */
export function currentPhase(): 'input' | 'view' {
  const el = document.activeElement as HTMLElement | null
  if (!el) return 'view'
  const tag = el.tagName
  return tag === 'TEXTAREA' || tag === 'INPUT' || tag === 'SELECT' || el.isContentEditable ? 'input' : 'view'
}
